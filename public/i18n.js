function getLang() {
  try {
    const l = JSON.parse(localStorage.getItem('lang'));
    if (l in STRINGS) return l;
  } catch {}
  return 'en';
}

function setLang(lang) {
  if (!(lang in STRINGS)) lang = 'en';
  try { localStorage.setItem('lang', JSON.stringify(lang)); } catch {}
  applyI18n();
}

// t('chapters.count', { n: 5 }) → "5 chapters". Si falta una traducción, cae al inglés y luego a la clave.
function t(key, vars = {}) {
  const str = STRINGS[getLang()][key] ?? STRINGS.en[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}

// Rellena los textos marcados en el HTML:
//   data-i18n="clave" → texto · data-i18n-aria="clave" → aria-label · data-i18n-alt="clave" → alt
function applyI18n(root = document) {
  document.documentElement.lang = getLang();
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
  root.querySelectorAll('[data-i18n-alt]').forEach((el) => el.setAttribute('alt', t(el.dataset.i18nAlt)));
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder)));
  root.querySelectorAll('title[data-i18n]').forEach((el) => (document.title = el.textContent));
  document.dispatchEvent(new CustomEvent('langchange'));
}
